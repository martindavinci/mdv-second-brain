'use strict';
const fs = require('node:fs');
const path = require('node:path');
const boards = require('./boards');

const TEXT = {
  en: { general: 'General', bugs: 'Bugs', features: 'Features', noIssues: 'No open issues.', noFeatures: 'No features yet.', open: 'open', generated: 'Generated by mdv-second-brain from the notes: do not edit by hand.' },
  it: { general: 'Generale', bugs: 'Bugs', features: 'Features', noIssues: 'Nessuna issue aperta.', noFeatures: 'Ancora nessuna feature.', open: 'aperte', generated: 'Generato da mdv-second-brain dalle note: non modificare a mano.' },
};
const LIFECYCLES = ['available', 'proposed', 'retired'];

const t = (ctx) => TEXT[ctx.lang] || TEXT.en;

function groupBy(items, key) {
  const m = new Map();
  for (const i of items) {
    const k = i[key] || '';
    if (!m.has(k)) m.set(k, []);
    m.get(k).push(i);
  }
  // projects alphabetically, the no-project group last
  return [...m.entries()].sort(([a], [b]) => (a === '') - (b === '') || a.localeCompare(b));
}

function featureNotes(ctx) {
  const tasks = require('./tasks');
  return tasks.itemFiles(ctx.vault, ['feature']).map((file) => {
    const { data } = tasks.readNote(file);
    return { name: path.basename(file, '.md'), project: tasks.projectOfNote(file, data), lifecycle: data.lifecycle || 'proposed' };
  });
}

function write(file, text) {
  fs.mkdirSync(path.dirname(file), { recursive: true });
  if (!fs.existsSync(file) || fs.readFileSync(file, 'utf8') !== text) fs.writeFileSync(file, text);
}

const header = (ctx, title) => `<!-- ${t(ctx).generated} -->\n# ${title}\n`;

function bugLines(items) {
  return items.sort((a, b) => a.name.localeCompare(b.name)).map((i) => `- [[${i.name}]] — ${i.status}${i.blocked ? ' 🔒' : ''}`).join('\n');
}

function featureBlock(items) {
  const parts = [];
  const known = new Set(LIFECYCLES);
  const order = [...LIFECYCLES, ...[...new Set(items.map((i) => i.lifecycle))].filter((l) => !known.has(l)).sort()];
  for (const l of order) {
    const of = items.filter((i) => i.lifecycle === l).sort((a, b) => a.name.localeCompare(b.name));
    if (of.length) parts.push(`### ${l}\n\n${of.map((i) => `- [[${i.name}]]`).join('\n')}`);
  }
  return parts.join('\n\n');
}

function rebuildIndexes(ctx) {
  const tasks = require('./tasks');
  const T = t(ctx);
  const split = new Set(boards.listBoards(ctx).map((b) => b.project).filter(Boolean));
  const issues = tasks.listItems(ctx, { kind: 'issue' }).filter((i) => i.status !== 'completed' && i.status !== 'discarded');
  const features = featureNotes(ctx);
  const inbox = path.join(ctx.vault, '00_Inbox');
  const splitOf = (p) => (p && split.has(p) ? p : null);

  const bugParts = [];
  for (const [p, items] of groupBy(issues.filter((i) => !splitOf(i.project)), 'project')) bugParts.push(`## ${p || T.general}\n\n${bugLines(items)}`);
  for (const p of [...split].sort()) {
    const n = issues.filter((i) => i.project === p).length;
    bugParts.push(`## ${p}\n\n- [[${p} ${T.bugs}]] — ${n} ${T.open}`);
    const own = issues.filter((i) => i.project === p);
    write(path.join(inbox, p, `${p} ${T.bugs}.md`), `${header(ctx, `${p} ${T.bugs}`)}\n${own.length ? bugLines(own) : T.noIssues}\n`);
  }
  write(path.join(inbox, `${T.bugs}.md`), `${header(ctx, T.bugs)}\n${bugParts.length ? bugParts.join('\n\n') : T.noIssues}\n`);

  const featParts = [];
  for (const [p, items] of groupBy(features.filter((f) => !splitOf(f.project)), 'project')) featParts.push(`## ${p || T.general}\n\n${featureBlock(items)}`);
  for (const p of [...split].sort()) {
    featParts.push(`## ${p}\n\n- [[${p} ${T.features}]]`);
    const own = features.filter((f) => f.project === p);
    write(path.join(inbox, p, `${p} ${T.features}.md`), `${header(ctx, `${p} ${T.features}`)}\n${own.length ? featureBlock(own) : T.noFeatures}\n`);
  }
  write(path.join(inbox, `${T.features}.md`), `${header(ctx, T.features)}\n${featParts.length ? featParts.join('\n\n') : T.noFeatures}\n`);
}

module.exports = { rebuildIndexes, featureNotes, TEXT };
