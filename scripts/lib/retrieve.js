'use strict';
// Bounded reads for the agent: a compact project context and a ranked search.
const fs = require('node:fs');
const path = require('node:path');
const frontmatter = require('./frontmatter');
const { projectName, unwrapLink } = require('./names');

const CONTEXT_MAX = 2500;
const SKIP_TOP = new Set(['80_Assets', 'node_modules']);
const GENERATED = /^<!-- (Generated by|Generato da) mdv-second-brain/;

const clip = (s, n) => (s.length > n ? s.slice(0, n - 1) + '…' : s);

function firstStateLine(body) {
  const tasks = require('./tasks');
  const sec = tasks.sectionOf(body, 'Status') || tasks.sectionOf(body, 'Stato') || '';
  return sec.split('\n').slice(1).find((l) => l.trim()) || '';
}

function context(ctx, project) {
  const tasks = require('./tasks');
  const ideas = require('./ideas');
  const p = project ? projectName(project) : null;
  const out = [];
  if (p) {
    const hub = path.join(ctx.vault, '20_Projects', p, `${p}.md`);
    if (fs.existsSync(hub)) {
      const body = frontmatter.parse(fs.readFileSync(hub, 'utf8')).body;
      const lines = body.split('\n');
      const heads = lines.filter((l) => /^## /.test(l));
      const para = [];
      for (const l of lines.slice(lines.findIndex((x) => /^# /.test(x)) + 1)) {
        if (/^#/.test(l)) break;
        if (l.trim() || para.length) para.push(l);
      }
      out.push(`project ${p} — hub 20_Projects/${p}/${p}.md`, clip(para.join('\n').trim(), 800), `sections: ${heads.join(' · ') || 'none'}`);
    } else out.push(`project ${p} — no hub yet`);
  } else out.push('workspace level (no project)');
  const all = tasks.listItems(ctx, p ? { project: p } : {});
  const active = all.filter((i) => i.status === 'in-progress' || i.status === 'todo');
  if (active.length) {
    out.push('work:');
    for (const i of active.slice(0, 10)) out.push(clip(`- ${i.name} [${i.status}]${i.blocked ? ' 🔒' : ''}${!p && i.project ? ` (${i.project})` : ''} — ${firstStateLine(tasks.readNote(i.file).body)}`, 180));
    if (active.length > 10) out.push(`+${active.length - 10} more (task list --project ${p || ''})`.replace(' --project )', ')'));
  }
  const bugs = all.filter((i) => i.kind === 'issue' && i.status !== 'completed' && i.status !== 'discarded').length;
  const openIdeas = ideas.listIdeas(ctx, { project: p || undefined, open: true, limit: 0 }).filter((i) => p || !i.project).length;
  out.push(`open bugs: ${bugs} · open ideas: ${openIdeas}`);
  try {
    for (const o of JSON.parse(fs.readFileSync(path.join(ctx.vault, '.brain', 'oversize.json'), 'utf8'))) out.push(`oversize: ${o.file} (${o.chars}/${o.budget}) — distil it`);
  } catch {}
  return clip(out.filter(Boolean).join('\n'), CONTEXT_MAX);
}

function walk(dir, top, archive, out) {
  let entries = [];
  try {
    entries = fs.readdirSync(dir, { withFileTypes: true });
  } catch {
    return out;
  }
  for (const e of entries) {
    if (e.name.startsWith('.')) continue;
    const full = path.join(dir, e.name);
    if (e.isDirectory()) {
      if (top && (SKIP_TOP.has(e.name) || (!archive && e.name === '90_Archive'))) continue;
      walk(full, false, archive, out);
    } else if (e.name.endsWith('.md')) out.push(full);
  }
  return out;
}

function search(ctx, query, { project, type, limit = 10, archive = false } = {}) {
  const tasks = require('./tasks');
  const terms = String(query || '').toLowerCase().split(/\s+/).filter(Boolean);
  if (!terms.length) return [];
  const has = (s) => terms.every((t) => s.toLowerCase().includes(t));
  const wantProject = project ? projectName(project).toLowerCase() : null;
  const hits = [];
  for (const file of walk(ctx.vault, true, archive, [])) {
    const text = fs.readFileSync(file, 'utf8');
    if (GENERATED.test(text)) continue;
    const { data, body } = frontmatter.parse(text);
    const name = path.basename(file, '.md');
    const kind = tasks.kindOf(file, data);
    if (type && kind !== type) continue;
    if (wantProject) {
      const rel = path.relative(ctx.vault, file).split(path.sep);
      const p = (unwrapLink(data.project) || (rel[0] === '20_Projects' ? rel[1] : '') || '').toLowerCase();
      if (p !== wantProject) continue;
    }
    let best = null;
    const consider = (score, heading, line) => {
      if (!best || score > best.score) best = { score, heading, snippet: clip(line.trim(), 200) };
    };
    if (has(name)) consider(100, '', name);
    let heading = '';
    let inLog = false;
    for (const line of body.split('\n')) {
      const h = /^#{1,6}\s+(.*)$/.exec(line);
      if (h) {
        heading = h[1].trim();
        inLog = /^log$/i.test(heading);
        if (has(heading)) consider(10, heading, line);
        continue;
      }
      if (line.trim() && has(line)) consider(inLog ? 0.5 : 1, heading, line);
    }
    if (best) hits.push({ path: path.relative(ctx.vault, file).replace(/\\/g, '/'), name, heading: best.heading, snippet: best.snippet, score: best.score });
  }
  return hits
    .sort((a, b) => b.score - a.score || a.path.localeCompare(b.path))
    .slice(0, limit > 0 ? limit : undefined)
    .map(({ score, ...h }) => h);
}

module.exports = { context, search, CONTEXT_MAX };
